import os
import json
import random
from datetime import datetime, UTC  # Explicitly importing the modern UTC object

def monitor_system_metrics(cycles: int = 5, cpu_threshold: float = 85.0) -> str:
    """
    Simulates real-time telemetry streaming from a cloud microservice.
    Parses JSON data streams, evaluates metrics against infrastructure thresholds,
    and logs critical anomalies using modern timezone-aware UTC objects.
    """
    # Modern approach: Using datetime.now(UTC) instead of the deprecated utcnow()
    current_utc_time = datetime.now(UTC)
    alert_log_path = f"infra_alerts_{current_utc_time.strftime('%Y%m%d')}.json"
    incidents_captured = []

    print(f"[{current_utc_time.isoformat()}] Initializing Infrastructure Health Engine...")
    print(f"Monitoring active telemetry streams. Alert Threshold: CPU > {cpu_threshold}%\n")

    for cycle in range(1, cycles + 1):
        # Simulating structured telemetry payloads typically generated by Docker/Kubernetes
        telemetry_payload = {
            "timestamp": datetime.now(UTC).isoformat(),
            "service_id": f"auth-service-us-east-{random.randint(10, 99)}",
            "metrics": {
                "cpu_utilization_pct": round(random.uniform(50.0, 98.0), 2),
                "memory_utilization_pct": round(random.uniform(60.0, 90.0), 2),
                "network_latency_ms": random.randint(15, 120)
            },
            "status": "HEALTHY"
        }

        current_cpu = telemetry_payload["metrics"]["cpu_utilization_pct"]
        
        # Threshold breach logic mimicking modern site reliability engineering metrics
        if current_cpu > cpu_threshold:
            telemetry_payload["status"] = "CRITICAL"
            alert_entry = {
                "alert_id": f"ERR-CPU-{random.randint(1000, 9999)}",
                "trigger_time": telemetry_payload["timestamp"],
                "offending_service": telemetry_payload["service_id"],
                "metrics_captured": telemetry_payload["metrics"],
                "severity": "HIGH"
            }
            incidents_captured.append(alert_entry)
            print(f" ALERT: Resource starvation detected on {telemetry_payload['service_id']}! CPU: {current_cpu}%")
        else:
            print(f" [Cycle {cycle}] System stable. {telemetry_payload['service_id']} CPU usage: {current_cpu}%")

    # Persisting structured incident telemetry for downstream DevOps ingestion
    if incidents_captured:
        try:
            with open(alert_log_path, 'w', encoding='utf-8') as stream:
                json.dump({"anomalies": incidents_captured}, stream, indent=4)
            print(f"\n[Success] Telemetry engine completed. {len(incidents_captured)} anomalies archived in '{alert_log_path}'.")
        except IOError as io_error:
            print(f"\n[Critical Error] I/O operational failure. Telemetry writing aborted: {io_error}")
    else:
        print("\n Monitoring cycle concluded. Zero threshold anomalies detected.")
        
    return alert_log_path

if __name__ == "__main__":
    # Execute with type-checked inputs to simulate enterprise test vectors   
    monitor_system_metrics(cycles=5, cpu_threshold=80.0)
